"""Read raw planes from the already installed Pillow/libavif oracle.

Only call this on small fixtures generated by verify.py, never on malformed cases
or user files. Uses public opaque-handle APIs, not private C structure layouts.
No native library is installed or added to File Forge.
"""
# Core
import ctypes
from functools import cache


@cache
def _library():
    # Core
    from PIL import _avif

    lib = ctypes.CDLL(_avif.__file__)
    void = ctypes.c_void_p
    signatures = {
        "avifVersion": (ctypes.c_char_p, []),
        "avifLibYUVVersion": (ctypes.c_uint, []),
        "avifCodecVersions": (None, [ctypes.c_char_p]),
        "avifImageCreateEmpty": (void, []),
        "avifDecoderCreate": (void, []),
        "avifImageDestroy": (None, [void]),
        "avifDecoderDestroy": (None, [void]),
        "avifDecoderReadMemory": (ctypes.c_int, [void, void, ctypes.c_char_p, ctypes.c_size_t]),
        "avifImageUsesU16": (ctypes.c_int, [void]),
        "avifImagePlane": (void, [void, ctypes.c_int]),
        "avifImagePlaneWidth": (ctypes.c_uint32, [void, ctypes.c_int]),
        "avifImagePlaneHeight": (ctypes.c_uint32, [void, ctypes.c_int]),
        "avifImagePlaneRowBytes": (ctypes.c_uint32, [void, ctypes.c_int]),
    }
    for name, (result, arguments) in signatures.items():
        function = getattr(lib, name)
        function.restype = result
        function.argtypes = arguments
    if lib.avifVersion() != b"1.4.2":
        raise RuntimeError("plane oracle requires the reviewed libavif 1.4.2 public API")
    return lib


def oracle_versions():
    lib = _library()
    codecs = ctypes.create_string_buffer(256)
    lib.avifCodecVersions(codecs)
    return {"libavif": lib.avifVersion().decode(), "libyuv": lib.avifLibYUVVersion(),
            "codecs": codecs.value.decode()}


def decode_planes(encoded):
    lib = _library()
    image = lib.avifImageCreateEmpty()
    decoder = lib.avifDecoderCreate()
    try:
        if not image or not decoder:
            raise MemoryError("oracle allocation failed")
        status = lib.avifDecoderReadMemory(decoder, image, encoded, len(encoded))
        if status or lib.avifImageUsesU16(image):
            raise ValueError(f"oracle requires a valid owned 8-bit still (status {status})")
        planes = {}
        for channel in range(4):
            pointer = lib.avifImagePlane(image, channel)
            if not pointer:
                continue
            width = lib.avifImagePlaneWidth(image, channel)
            height = lib.avifImagePlaneHeight(image, channel)
            stride = lib.avifImagePlaneRowBytes(image, channel)
            if not 0 < width * height <= 65536 or not width <= stride <= 65536:
                raise ValueError("oracle plane exceeds small fixture bounds")
            samples = b"".join(ctypes.string_at(pointer + row * stride, width) for row in range(height))
            planes[channel] = (width, height, samples)
        return planes
    finally:
        if decoder:
            lib.avifDecoderDestroy(decoder)
        if image:
            lib.avifImageDestroy(image)


def compare_planes(fields, reference):
    """Require exact geometry, plane set and every sample; no digest-only equality."""
    try:
        actual_channels = {int(key.split("_")[1]) for key in fields if key.startswith("plane_") and key.endswith("_hex")}
        if actual_channels != set(reference):
            return False
        for channel, (width, height, samples) in reference.items():
            if (int(fields[f"plane_{channel}_width"]), int(fields[f"plane_{channel}_height"])) != (width, height):
                return False
            if bytes.fromhex(fields[f"plane_{channel}_hex"]) != samples:
                return False
    except (KeyError, ValueError):
        return False
    return True
